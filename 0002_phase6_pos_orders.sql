create or replace function public.create_restaurant_order(
  p_location_id uuid,
  p_order_type text,
  p_payment_method text,
  p_items jsonb,
  p_notes text default null
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_org uuid;
  v_order_id uuid;
  v_subtotal numeric(12,2) := 0;
  v_item record;
  v_menu_item public.menu_items%rowtype;
begin
  if v_user is null then raise exception 'You must be signed in.'; end if;
  if p_order_type not in ('counter','dine_in','takeaway') then raise exception 'Invalid order type.'; end if;
  if p_payment_method not in ('unpaid','cash','upi','card') then raise exception 'Invalid payment method.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then raise exception 'Add at least one item.'; end if;

  select organization_id into v_org
  from public.organization_members
  where user_id=v_user and status='active'
  order by created_at asc limit 1;

  if v_org is null then raise exception 'No active restaurant workspace found.'; end if;

  if not exists (select 1 from public.locations where id=p_location_id and organization_id=v_org) then
    raise exception 'Selected outlet does not belong to your workspace.';
  end if;

  for v_item in select * from jsonb_to_recordset(p_items) as x(menu_item_id uuid, quantity integer)
  loop
    if v_item.quantity is null or v_item.quantity < 1 or v_item.quantity > 99 then raise exception 'Invalid item quantity.'; end if;
    select * into v_menu_item from public.menu_items
      where id=v_item.menu_item_id and organization_id=v_org and is_available=true;
    if not found then raise exception 'A menu item is unavailable or does not belong to this restaurant.'; end if;
    v_subtotal := v_subtotal + (v_menu_item.price * v_item.quantity);
  end loop;

  insert into public.restaurant_orders(
    organization_id, location_id, order_type, payment_method, payment_status,
    subtotal, total, notes, created_by
  ) values (
    v_org, p_location_id, p_order_type, p_payment_method,
    case when p_payment_method='unpaid' then 'pending' else 'paid' end,
    v_subtotal, v_subtotal, nullif(trim(p_notes),''), v_user
  ) returning id into v_order_id;

  for v_item in select * from jsonb_to_recordset(p_items) as x(menu_item_id uuid, quantity integer)
  loop
    select * into v_menu_item from public.menu_items where id=v_item.menu_item_id and organization_id=v_org;
    insert into public.restaurant_order_items(order_id, menu_item_id, item_name, unit_price, quantity, line_total)
    values(v_order_id, v_menu_item.id, v_menu_item.name, v_menu_item.price, v_item.quantity, v_menu_item.price*v_item.quantity);
  end loop;

  return v_order_id;
end;
$$;

revoke all on function public.create_restaurant_order(uuid,text,text,jsonb,text) from public;
grant execute on function public.create_restaurant_order(uuid,text,text,jsonb,text) to authenticated;

grant select, insert, update, delete on public.menu_categories to authenticated;
