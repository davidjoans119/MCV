create table if not exists public.menu_categories (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  name text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (organization_id, name)
);

create table if not exists public.menu_items (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  category_id uuid references public.menu_categories(id) on delete set null,
  name text not null,
  price numeric(12,2) not null check (price >= 0),
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.restaurant_orders (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  location_id uuid not null references public.locations(id),
  order_number bigint generated by default as identity,
  order_type text not null default 'counter' check (order_type in ('counter','dine_in','takeaway')),
  status text not null default 'placed' check (status in ('placed','preparing','ready','completed','cancelled')),
  payment_method text not null default 'unpaid' check (payment_method in ('unpaid','cash','upi','card')),
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','refunded')),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  total numeric(12,2) not null check (total >= 0),
  notes text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.restaurant_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.restaurant_orders(id) on delete cascade,
  menu_item_id uuid references public.menu_items(id) on delete set null,
  item_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12,2) not null check (line_total >= 0)
);

create index if not exists idx_menu_items_org on public.menu_items(organization_id);
create index if not exists idx_orders_org_created on public.restaurant_orders(organization_id, created_at desc);
create index if not exists idx_orders_location_created on public.restaurant_orders(location_id, created_at desc);
create index if not exists idx_order_items_order on public.restaurant_order_items(order_id);

alter table public.menu_categories enable row level security;
alter table public.menu_items enable row level security;
alter table public.restaurant_orders enable row level security;
alter table public.restaurant_order_items enable row level security;

